"""
Build helios/gui/static/css/tailwind.css, the Tailwind CSS 3.4.17 utilities the dashboard
uses, from packaging/tailwind.config.js (dev-time step; the generated file is committed,
so the app needs neither Node nor network at run time).

    python scripts/build_css.py           # needs Node.js; runs `npx tailwindcss@3.4.17`
    TAILWIND_CLI=path/to/tailwindcss python scripts/build_css.py

The first lines of the output record the SHA-256 of the inputs (config, page and
scripts); tests/test_gui_js.py fails when the page or a script changed without a rebuild.
"""
import hashlib
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / "packaging" / "tailwind.config.js"
INPUT = ROOT / "packaging" / "tailwind.input.css"
OUTPUT = ROOT / "helios" / "gui" / "static" / "css" / "tailwind.css"
VERSION = "3.4.17"


def content_files():
    """The files listed in the config's content (relative to packaging/)."""
    text = CONFIG.read_text(encoding="utf-8")
    return [(CONFIG.parent / m).resolve() for m in re.findall(r"'(\.\./helios/gui/static/[^']+)'", text)]


def inputs_digest() -> str:
    h = hashlib.sha256()
    for path in [CONFIG, INPUT] + content_files():
        h.update(path.relative_to(ROOT).as_posix().encode())
        h.update(path.read_bytes().replace(b"\r\n", b"\n"))
    return h.hexdigest()


def main():
    cli = os.environ.get("TAILWIND_CLI")
    if cli:
        cmd = [cli]
    else:
        npx = shutil.which("npx") or shutil.which("npx.cmd")
        if not npx:
            sys.exit("Node.js (npx) is needed to build the CSS, or set TAILWIND_CLI to a tailwindcss executable.")
        cmd = [npx, "--yes", f"tailwindcss@{VERSION}"]
    tmp = OUTPUT.with_suffix(".tmp.css")
    subprocess.run(cmd + ["-c", str(CONFIG), "-i", str(INPUT), "-o", str(tmp), "--minify"], check=True, cwd=ROOT)
    css = tmp.read_text(encoding="utf-8")
    tmp.unlink()
    header = (f"/* Generated by scripts/build_css.py with Tailwind CSS {VERSION} (MIT licence). Do not edit.\n"
              f"   inputs-sha256: {inputs_digest()} */\n")
    OUTPUT.write_text(header + css + "\n", encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({OUTPUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
