"""
The Richardson & Cane list of near-Earth interplanetary coronal mass ejections (ICMEs)
since 1996, and cross-matching of times (storms, shocks, magnetic cloud candidates)
with it.

Source: I. G. Richardson and H. V. Cane, "Near-Earth Interplanetary Coronal Mass Ejections
Since January 1996", https://izw1.caltech.edu/ACE/ASC/DATA/level3/icmetable2.htm, also
published on Harvard Dataverse, doi:10.7910/DVN/C2MHTH (licence CC0 1.0). The authors ask
that the DOI be cited, with Cane & Richardson (2003, JGR 108, 1156) and Richardson & Cane
(2010, Sol. Phys. 264, 189).

A snapshot of the table is bundled (helios/data/icme_richardson_cane.json, made with
scripts/update_icme_catalog.py) so the cross-match works offline; when the network is
available the live page is read (cached for a week) and used instead.

Columns of the table (footnotes of the page): (a) disturbance: storm sudden commencement
at Earth, or the shock at ACE ('A'), WIND ('W'), SOHO ('S'), or the estimated arrival of
the disturbance; (b) ICME start and end from plasma and field data, to about an hour;
(c) composition/charge-state boundaries and (d) magnetic cloud boundaries, in hours
relative to (b); (e) bidirectional electrons; (f) bidirectional ions; (g) boundary quality
1-3, 'W' weak signatures; (h) speed increase at the disturbance, 'S' a reported fast
forward shock; (i) mean ICME speed; (j) maximum speed from (a) to the ICME end; (k) mean
|B|; (l) magnetic cloud: 2 reported cloud, 1 rotation only, 0 none ('H' Huttunen et al.
2005); (m) minimum Dst from (a) to the ICME end "or slightly thereafter", 'P'
provisional, 'Q' quicklook, otherwise final; (n) transit speed; (o) associated CME.
"""
from __future__ import annotations

import html
import json
import re
import threading
import time
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

SOURCE_URL = "https://izw1.caltech.edu/ACE/ASC/DATA/level3/icmetable2.htm"
DOI = "10.7910/DVN/C2MHTH"
LICENCE = "CC0 1.0 (Harvard Dataverse)"
CITATION = ("Richardson, I. G. & Cane, H. V., Near-Earth Interplanetary Coronal Mass Ejections Since January 1996, "
            "doi:10.7910/DVN/C2MHTH; Cane & Richardson (2003), JGR 108, 1156; Richardson & Cane (2010), Sol. Phys. 264, 189")
SNAPSHOT = Path(__file__).resolve().parent.parent / "data" / "icme_richardson_cane.json"
CACHE_MAX_AGE_S = 7 * 24 * 3600
# Hours after the ICME trailing edge still counted for its storm: the list gives the
# minimum Dst from the disturbance to the trailing edge "or slightly thereafter if the
# storm peak is generated by the trailing regions of the ICME".
DEFAULT_AFTER_HOURS = 3.0

_lock = threading.Lock()
_loaded: Dict[str, Any] = {}

_DT = re.compile(r"(\d{4})/(\d{1,2})/(\d{1,2})\s+(\d{2})(\d{2})")


def _time(text: str) -> Optional[datetime]:
    m = _DT.search(text or "")
    if not m:
        return None
    y, mo, d, h, mi = (int(x) for x in m.groups())
    t = datetime(y, mo, d, tzinfo=timezone.utc)
    return t + timedelta(hours=h, minutes=mi)  # 2400 would be the next day


def _number(text: str) -> Optional[float]:
    m = re.match(r"\s*([+-]?\d+(?:\.\d+)?)", text or "")
    return float(m.group(1)) if m else None


def _offset(text: str):
    """Boundary offset in hours, or the page's codes 'ns' (no signature) / 'nc' (not clear)."""
    t = (text or "").strip()
    if t in ("ns", "nc"):
        return t
    return _number(t)


def parse_table(page: str) -> List[Dict[str, Any]]:
    """The ICMEs of the page, oldest first (rows with fewer than 17 cells are headers)."""
    events = []
    for row in re.findall(r"<tr[^>]*>(.*?)</tr>", page, flags=re.S | re.I):
        cells = [html.unescape(re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", c))).strip()
                 for c in re.split(r"<td[^>]*>", row, flags=re.I)[1:]]  # some last cells lack </td>
        if len(cells) < 17 or cells[0].startswith("Disturbance"):
            continue
        dist, start, end = _time(cells[0]), _time(cells[1]), _time(cells[2])
        if start is None or end is None:
            continue
        src = re.search(r"\(([AWS])\)", cells[0])
        dv = cells[10]
        dst = cells[15]
        mc = cells[14]
        events.append({
            "disturbance": (dist or start).strftime("%Y-%m-%d %H:%M"),
            "disturbance_source": {"A": "shock at ACE", "W": "shock at WIND", "S": "SOHO shock candidate"}.get(
                src.group(1) if src else "", "sudden commencement or disturbance arrival" if dist else "ICME start"),
            "icme_start": start.strftime("%Y-%m-%d %H:%M"),
            "icme_end": end.strftime("%Y-%m-%d %H:%M"),
            "composition_offsets_h": [_offset(cells[3]), _offset(cells[4])],
            "magnetic_cloud_offsets_h": [_offset(cells[5]), _offset(re.sub(r"\(.*\)", "", cells[6]))],
            "two_magnetic_clouds": "2 MCs" in cells[6],
            "bidirectional_electrons": cells[7] if cells[7] not in ("...", "..") else None,
            "bidirectional_ions": cells[8] if cells[8] not in ("...", "..") else None,
            "quality": int(_number(cells[9])) if _number(cells[9]) is not None else None,
            "weak_signatures": "W" in cells[9],
            "speed_jump_kms": _number(dv),
            "fast_forward_shock": bool(re.search(r"\bS\b", dv)),
            "v_icme_kms": _number(cells[11]),
            "v_max_kms": _number(cells[12]),
            "b_mean_nt": _number(cells[13]),
            "magnetic_cloud": int(_number(mc)) if _number(mc) is not None else None,
            "huttunen_2005": "H" in mc,
            "dst_min_nt": _number(dst),
            "dst_kind": "quicklook" if "Q" in dst else ("provisional" if "P" in dst else "final"),
            "v_transit_kms": cells[16] if cells[16] not in ("...", "") else None,
            "cme": (cells[17] if len(cells) > 17 and cells[17] not in ("...", "", "�") else None),
        })
    events.sort(key=lambda e: e["icme_start"])
    return events


def revision(page: str) -> Optional[str]:
    m = re.search(r"Revised\s+([A-Z][a-z]+\s+\d{1,2},\s+\d{4})", re.sub(r"<[^>]+>", " ", page))
    return re.sub(r"\s+", " ", m.group(1)) if m else None


def _snapshot() -> Dict[str, Any]:
    data = json.loads(SNAPSHOT.read_text(encoding="utf-8"))
    data["origin"] = "bundled snapshot"
    return data


def _fetch_live(cache_dir: Path) -> Optional[Dict[str, Any]]:
    """The live page (cached for CACHE_MAX_AGE_S), parsed; None when it cannot be read."""
    path = cache_dir / "catalogs" / "icmetable2.htm"
    page = None
    try:
        if path.exists() and time.time() - path.stat().st_mtime < CACHE_MAX_AGE_S:
            page = path.read_text(encoding="cp1252", errors="replace")
    except OSError:
        page = None
    if page is None:
        try:
            import httpx
            from helios.core.downloader import _ssl_context
            r = httpx.get(SOURCE_URL, timeout=30.0, verify=_ssl_context(), follow_redirects=True)
            r.raise_for_status()
            page = r.content.decode("cp1252", errors="replace")
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(page, encoding="cp1252", errors="replace")
        except Exception:  # offline, moved page: the bundled snapshot is used
            return None
    events = parse_table(page)
    if len(events) < 500:  # not the table we know (page redesigned): do not trust it
        return None
    return {"events": events, "revision": revision(page), "source": SOURCE_URL, "doi": DOI,
            "licence": LICENCE, "citation": CITATION, "origin": "live page, cached for a week"}


def load(cache_dir: Optional[Path] = None, live: bool = True) -> Dict[str, Any]:
    """The catalogue: the live page when it can be read and live is True, else the snapshot."""
    key = "live" if live else "snapshot"
    with _lock:
        hit = _loaded.get(key)
        if hit and time.time() - hit[0] < 3600:
            return hit[1]
        data = None
        if live and cache_dir is not None:
            data = _fetch_live(cache_dir)
        if data is None:
            data = _snapshot()
        _loaded[key] = (time.time(), data)
        return data


def _dt(s: str) -> datetime:
    return datetime.strptime(s, "%Y-%m-%d %H:%M").replace(tzinfo=timezone.utc)


def events_between(events: List[Dict[str, Any]], start: datetime, end: datetime) -> List[Dict[str, Any]]:
    """ICMEs whose interval from the disturbance (or the ICME start, if earlier) to the end overlaps [start, end]."""
    return [e for e in events if min(_dt(e["disturbance"]), _dt(e["icme_start"])) <= end and _dt(e["icme_end"]) >= start]


def locate(events: List[Dict[str, Any]], t: datetime, after_hours: float = DEFAULT_AFTER_HOURS) -> Optional[Dict[str, Any]]:
    """
    Where a time falls relative to the listed ICMEs: in the 'sheath' (from the disturbance
    to the ICME start), in the 'ICME' itself, or 'after' the trailing edge (within
    ``after_hours``). Inside the ICME wins over another ICME's sheath; None when no ICME.
    """
    best = None
    rank = {"ICME": 0, "sheath": 1, "after": 2}
    for e in events:
        d, s, en = _dt(e["disturbance"]), _dt(e["icme_start"]), _dt(e["icme_end"])
        if s <= t <= en:
            region = "ICME"
        elif min(d, s) <= t < s:
            region = "sheath"
        elif en < t <= en + timedelta(hours=after_hours):
            region = "after"
        else:
            continue
        if best is None or rank[region] < rank[best["region"]]:
            best = {"region": region, "event": e}
    return best


def summary(e: Dict[str, Any]) -> Dict[str, Any]:
    """The fields shown next to a cross-matched time."""
    return {k: e[k] for k in ("disturbance", "icme_start", "icme_end", "magnetic_cloud", "fast_forward_shock",
                              "quality", "dst_min_nt", "dst_kind", "v_icme_kms", "cme")}


def annotate_storms(storms: List[Dict[str, Any]], events: List[Dict[str, Any]],
                    after_hours: float = DEFAULT_AFTER_HOURS) -> Dict[str, Any]:
    """
    Add to each storm (helios.core.omni_statistics.find_storms) the listed ICME in whose
    sheath, body or trailing ``after_hours`` the Dst minimum falls (the middle of the
    hourly average is used: hourly Dst is stamped at the start of its hour). Returns the
    number of storms in each region.
    """
    counts = {"sheath": 0, "ICME": 0, "after": 0, "none": 0}
    for s in storms:
        t = datetime.strptime(s["minimum_time"], "%Y-%m-%d %H:%M").replace(tzinfo=timezone.utc) + timedelta(minutes=30)
        hit = locate(events, t, after_hours)
        s["icme"] = None if hit is None else {"region": hit["region"], **summary(hit["event"])}
        counts[hit["region"] if hit else "none"] += 1
    return counts
